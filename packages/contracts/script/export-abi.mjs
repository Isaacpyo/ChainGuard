#!/usr/bin/env node
// Copies the compiled GuardedVault ABI + bytecode into packages/shared so the API and
// web app never need a Solidity toolchain. Run after `forge build`; CI fails if stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = resolve(here, '../out/GuardedVault.sol/GuardedVault.json');
const target = resolve(here, '../../shared/src/abi/guardedVault.ts');

const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
const source = `// Generated by packages/contracts/script/export-abi.mjs — do not edit by hand.
// Regenerate with: cd packages/contracts && forge build && cd ../.. && npm run abi

export const guardedVaultAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;

export const guardedVaultBytecode = '${artifact.bytecode.object}' as const;
`;
writeFileSync(target, source);
console.log(`wrote ${target} (${artifact.abi.length} ABI entries)`);
